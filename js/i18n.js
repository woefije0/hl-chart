function t(key, ...args) {
  const dict = I18N[state.lang] || I18N.en;
  const val = dict[key] !== undefined ? dict[key] : I18N.en[key];
  return typeof val === 'function' ? val(...args) : val;
}

function applyLanguage() {
  document.documentElement.lang = state.lang === 'kr' ? 'ko' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  $('langBtnEn').classList.toggle('active', state.lang === 'en');
  $('langBtnKr').classList.toggle('active', state.lang === 'kr');
  // 상태 문구(연결 대기/실시간 연결됨 등)는 data-i18n으로 관리하지 않고 현재 상태 키를 다시 번역해서 반영
  $('statusText').textContent = t(state.statusKey, ...state.statusArgs);
  // 동적으로 렌더링되는 목록/라벨들도 현재 언어로 다시 그림
  renderIntervalFavorites();
  renderChartTypeList();
  renderIndicatorsList();
  renderMaRibbonSettingsPanel();
  refreshPineVersionAutoOption();
  const ct = CHART_TYPES.find(x => x.id === state.chartType);
  if (ct) chartTypeLabel.textContent = t(ct.i18nKey);
  if (pairsDropdown.isOpen()) renderDropdownList(searchInput.value || '');

  if (state.hoverCandle) {
    renderCandleStats(state.hoverCandle, t('selectedCandle'));
  } else if (state.todayCandle) {
    renderCandleStats(state.todayCandle, t('today'));
  }
}
function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'kr') return;
  state.lang = lang;
  store.set('lang', lang);
  applyLanguage();
}
